export const ITEMS: Readonly<Record<string, ItemDef>> = Object.fromEntries(ITEM_LIST.map((def) => [def.id, def]));

/** Item ids in catalogue order. */
export const ITEM_ORDER: readonly string[] = ITEM_LIST.map((def) => def.id);

export function getItemDef(itemId: string): ItemDef {
  const def = ITEMS[itemId];
  if (!def) {
    throw new Error(`Unknown item: ${itemId}`);
  }
  return def;
}
